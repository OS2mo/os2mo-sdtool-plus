import asyncio
from uuid import UUID

import click

from scripts.common import get_gql_client
from sdtoolplus.autogenerated_graphql_client import EventRerunInput
from sdtoolplus.autogenerated_graphql_client import EventSendInput
from sdtoolplus.autogenerated_graphql_client import ListenerFilter
from sdtoolplus.autogenerated_graphql_client import NamespaceFilter
from sdtoolplus.models import OrgGraphQLEvent
from sdtoolplus.models import PersonAndEmploymentGraphQLEvent


def send(routing_key: str, subject: str, priority: int = 10000) -> None:
    gql_client = get_gql_client()
    asyncio.run(
        gql_client.send_event(
            EventSendInput(
                namespace="sd",
                routing_key=routing_key,
                subject=subject,
                priority=priority,
            )
        )
    )


@click.group()
def cli() -> None:
    """Send SD events to the OS2mo event system."""


@cli.command("ou")
@click.argument("institution_identifier", type=str)
@click.argument("org_unit", type=click.UUID)
@click.option(
    "--priority", type=int, default=9000, show_default=True, help="Event priority"
)
def org_unit(institution_identifier: str, org_unit: UUID, priority: int) -> None:
    """Send an org unit event."""
    send(
        routing_key="org",
        subject=OrgGraphQLEvent(
            institution_identifier=institution_identifier,
            org_unit=org_unit,
        ).json(),
        priority=priority,
    )


@cli.command("eng")
@click.argument("institution_identifier", type=str)
@click.argument("cpr", type=str)
@click.argument("employment_identifier", type=str)
def employment(
    institution_identifier: str, cpr: str, employment_identifier: str
) -> None:
    """Send a person and employment event."""
    send(
        routing_key="person-and-employment",
        subject=PersonAndEmploymentGraphQLEvent(
            institution_identifier=institution_identifier,
            cpr=cpr,
            employment_identifier=employment_identifier,
        ).json(),
    )


@cli.command()
@click.option(
    "--namespace", default="sd", show_default=True, help="Namespace of the events"
)
@click.option(
    "--routing-key",
    "routing_keys",
    multiple=True,
    help="Routing key of the events, e.g. 'org' (can be repeated)",
)
@click.option(
    "--subject",
    "subjects",
    multiple=True,
    help="Exact subject of the events (can be repeated)",
)
@click.option(
    "--priority",
    "priorities",
    type=int,
    multiple=True,
    help="Priority of the events (can be repeated)",
)
def rerun(
    namespace: str,
    routing_keys: tuple[str, ...],
    subjects: tuple[str, ...],
    priorities: tuple[int, ...],
) -> None:
    """
    Rerun the events matching all the given filters.

    Only events still in the queue can be rerun, i.e. events which have been
    processed successfully cannot be rerun. A single event can be rerun by its
    subject, which must match exactly, e.g.:

    \b
    sd-event rerun --subject '{"institution_identifier": "II", "org_unit": "11111111-1111-1111-1111-111111111111"}'
    """
    if not (routing_keys or subjects or priorities):
        click.confirm(
            f"No filters given. Rerun ALL events in the '{namespace}' namespace?",
            abort=True,
        )

    gql_client = get_gql_client()
    events = asyncio.run(
        gql_client.rerun_events(
            EventRerunInput(
                listeners=ListenerFilter(
                    namespaces=NamespaceFilter(names=[namespace]),
                    routing_keys=list(routing_keys) if routing_keys else None,
                ),
                subjects=list(subjects) if subjects else None,
                priorities=list(priorities) if priorities else None,
            )
        )
    )

    for event in events:
        click.echo(
            f"{event.listener.user_key} (priority {event.priority}): {event.subject}"
        )
    click.echo(f"{len(events)} event(s) rerun")


if __name__ == "__main__":
    cli(prog_name="sd-event")
