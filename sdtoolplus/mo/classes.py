from datetime import datetime
from datetime import time
from uuid import UUID

import structlog.stdlib

from sdtoolplus.autogenerated_graphql_client import ClassCreateInput
from sdtoolplus.autogenerated_graphql_client import GraphQLClient
from sdtoolplus.autogenerated_graphql_client import ValidityInput

logger = structlog.stdlib.get_logger()


async def create_class(
    graphql_client: GraphQLClient,
    user_key: str,
    scope: str,
    name: str,
    parent: UUID | None,
    facet_uuid: UUID,
    from_date: datetime,
) -> UUID:
    """Create a new class in MO"""

    logger.info(
        "Create class in MO",
        user_key=user_key,
        scope=scope,
        name=name,
        parent=parent,
        facet_uuid=facet_uuid,
    )

    # MO does not support datetimes with a time 🥲
    class_from = datetime.combine(from_date, time.min, from_date.tzinfo)

    create_input = ClassCreateInput(
        facet_uuid=facet_uuid,
        user_key=user_key,
        name=name,
        scope=scope,
        parent_uuid=parent,
        validity=ValidityInput(from_=class_from, to=None),
    )
    mo_class = await graphql_client.create_class(create_input)

    logger.info("Class created in MO", uuid=mo_class.uuid)

    return mo_class.uuid


